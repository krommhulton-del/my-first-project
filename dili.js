  // 兼向:方位角离八方中线超过 17°(即离分界不足 5.5°)时,算骑在两个方向之间
  function jianOf(deg) {
    const i = Math.round(deg / 45) % 8, center = Math.round(deg / 45) * 45;
    let d = deg - center; if (d > 180) d -= 360; if (d < -180) d += 360;
    if (Math.abs(d) <= 17) return null;
    return DIRS[((i + (d > 0 ? 1 : -1)) % 8 + 8) % 8];
  }

