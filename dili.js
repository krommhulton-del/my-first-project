  // 缘起:实测上海旺向为正北/正东/东南/正南时,江苏(锚南京,在上海西北)被整省判出局,
  // 可南通、盐城、连云港明明都在上海正北。这里改按省内各市实算,并把省内分歧标出来。
  function provinceView(chart, a, goodDirs, badDirs) {
    const out = [];
    for (const [pv, list] of Object.entries(PROV_CITIES)) {
      if (!list.length) continue;
      let good = 0, bad = 0, n = 0; const goodOnes = [];
      for (const c of list) {
        const p = PLACES.find(x => x[0] === c);
        if (!p || distKm(a, p) < 80) continue;
        n++;
        const d = dirOf(bearing(a, p));
        if (goodDirs.includes(d)) { good++; goodOnes.push({ name: c, dir: d, tier: tierOf(c), km: distKm(a, p) }); }
        else if (badDirs.includes(d)) bad++;
      }
      if (!n) continue;
      const ratio = good / n;
      out.push({ prov: pv, n, good, bad, ratio,
        split: ratio > 0.2 && ratio < 0.8,
        best: goodOnes.sort((x, y) => x.tier - y.tier || x.km - y.km).slice(0, 3) });
    }
    return out.sort((x, y) => y.ratio - x.ratio || y.n - x.n);
  }

