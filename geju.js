  function judge(chart) {
    const ge = takeGe(chart);
    const c = mk(chart);
    const rule = R[ge.key];
    const out = { ge, cheng: [], bai: [], jiu: [], ji: [], state: '', quote: QUOTE_ALL };
    if (!rule) { out.state = '此格本模块未收'; return out; }
    const run = (list, bag) => (list || []).forEach(r => { if (r.f(c, chart)) bag.push({ quote: r.q, why: r.w }); });
    run(rule.成, out.cheng); run(rule.败, out.bai); run(rule.忌, out.ji);
    // 救应只在确有「败」时才谈——没病就不必开药。自测缘起:曾出现「未见成败」却列着救应。
    if (out.bai.length) run(rule.救, out.jiu);

    if (out.cheng.length && !out.bai.length) out.state = out.ji.length ? '成中带忌' : '成';
    else if (out.bai.length && !out.cheng.length) out.state = out.jiu.length ? '败中有救' : '败';
    else if (out.cheng.length && out.bai.length) out.state = out.jiu.length ? '成败交见,有救应' : '成败交见';
    else out.state = '未见成败(四柱不曾照到这一格的成败条件)';
    return out;
  }

